#!/usr/bin/env python3
"""Build textdata.py: short, self-contained lines from a public-domain text (Project Gutenberg):
  #216  The Tao Teh King, tr. James Legge (1891)
Usage: python3 tools/build_texts.py pg216.txt > textdata.py   (run once; the output is committed)."""
import re
import sys

MAXLEN, MINLEN = 150, 30


def clean(s):
    for a, b in (("\u2019", "'"), ("\u2018", "'"), ("\u201c", '"'), ("\u201d", '"'), ("\u2014", "--"), ("\u2013", "-")):
        s = s.replace(a, b)
    s = re.sub(r"\s+", " ", s.replace("(", "").replace(")", "")).strip()
    return s.replace("'Tis", "'Tis").replace(" ;", ";").replace(" ,", ",")


def tao(path):
    txt = open(path, encoding="utf-8-sig").read()
    body = txt[txt.index("PART 1."):txt.index("*** END OF THE PROJECT GUTENBERG")]
    out, ch = [], 0
    for para in re.split(r"\n\s*\n", body):
        p = para.strip()
        if not p or p.startswith("PART"):
            continue
        m = re.match(r"^(?:Ch\. )?(\d+)\. (\d+)\.\s*(.*)$", p, re.S)
        if m:
            ch = int(m.group(1))
            p = m.group(3)
        else:
            p = re.sub(r"^\d+\.\s*", "", p, flags=re.S)
        if not ch or not p.strip():
            continue
        if para.startswith("   "):                      # rhymed verse block: keep as one line if short
            v = clean(p)
            if MINLEN <= len(v) <= MAXLEN:
                out.append((ch, v))
            continue
        p = clean(p)
        if MINLEN <= len(p) <= MAXLEN and p[0].isupper():
            out.append((ch, p))
            continue
        for s in re.split(r"(?<=[.;?!])\s+(?=[A-Z])", p):
            s = s.strip()
            if MINLEN <= len(s) <= MAXLEN and s[0].isupper() and s[-1] in ".?!":
                out.append((ch, s))
    seen, res = set(), []
    for ch, s in out:
        if s not in seen and len(s) >= 45 and all(32 <= ord(c) < 127 for c in s) and not s.lower().startswith(
                ("therefore", "hence", "so it is", "this is", "it is", "this ", "that ", "thus", "why", "how ", "such")):
            seen.add(s)
            res.append((ch, s))
    return res


def main():
    t = tao(sys.argv[1])
    print('"""Generated by tools/build_texts.py from Project Gutenberg #216 (Tao Teh King, tr. James Legge, 1891),')
    print('public domain. %d lines."""' % len(t))
    print("TAO = [")
    for ch, s in t:
        print("    (%d, %r)," % (ch, s))
    print("]")


if __name__ == "__main__":
    main()
